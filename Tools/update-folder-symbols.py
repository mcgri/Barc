#!/usr/bin/env python3
"""Refresh the pinned MIT-licensed Ionicons used by the folder icon picker."""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from urllib.request import urlopen
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
REVISION = "d1e2c48641fd5f4910ee42a144dc1c84b1a9a4ee"
BASE = f"https://raw.githubusercontent.com/ionic-team/ionicons/{REVISION}"
ICONS = [
    ("star", "Star"), ("bookmark", "Bookmark"), ("heart", "Heart"), ("flash", "Lightning"),
    ("triangle", "Triangle"), ("medical", "Asterisk"), ("notifications", "Bell"), ("bulb", "Light bulb"),
    ("chatbubble-ellipses", "Chat"), ("people", "People"), ("construct", "Tools"), ("egg", "Egg"),
    ("ellipse", "Circle"), ("moon", "Moon"), ("planet", "Planet"), ("leaf", "Leaf"),
    ("cloud", "Cloud"), ("paw", "Paw"), ("restaurant", "Cutlery"), ("airplane", "Airplane"),
    ("musical-note", "Music"), ("videocam", "Video"), ("code", "Code"), ("skull", "Skull"),
]

def fetch(path):
    with urlopen(f"{BASE}/{path}", timeout=30) as response:
        return response.read().decode("utf-8")

def asset(icon):
    name, title = icon
    svg = fetch(f"src/svg/{name}.svg").strip()
    root = ET.fromstring(svg)
    assert root.tag.endswith("svg") and len(svg) < 65536
    assert "<script" not in svg and "href=" not in svg
    return name, title, svg

with ThreadPoolExecutor(max_workers=8) as pool:
    assets = list(pool.map(asset, ICONS))

license_path = ROOT / "LICENSES/Ionicons.txt"
license_path.parent.mkdir(exist_ok=True)
license_path.write_text(fetch("LICENSE"))

source = '''// Modified for Barc: compact folder icon palette, 2026-10-24.
// SVG artwork: Ionicons, Copyright (c) 2015-present Ionic, MIT license.
// See LICENSES/Ionicons.txt. Generated by Tools/update-folder-symbols.py.
import AppKit

@MainActor
enum FolderSymbols {
    struct Choice {
        let name: String
        let title: String
        var storedName: String { "ionicon." + name }
    }

    static let choices: [Choice] = [
'''
source += "\n".join(f"        Choice(name: {json.dumps(n)}, title: {json.dumps(t)})," for n, t, _ in assets)
source += '''
    ]
    private static var cache: [String: NSImage] = [:]

    /// Existing SF Symbol names keep working alongside the bundled vector icons.
    static func image(named name: String, description: String? = nil) -> NSImage? {
        guard name.hasPrefix("ionicon.") else {
            return NSImage(systemSymbolName: name, accessibilityDescription: description)
        }
        let key = String(name.dropFirst("ionicon.".count))
        if let image = cache[key] { return image }
        guard let svg = artwork[key], let image = NSImage(data: Data(svg.utf8)) else { return nil }
        image.size = NSSize(width: 18, height: 18)
        image.isTemplate = true
        cache[key] = image
        return image
    }

    // Pinned source revision: ''' + REVISION + '''
    private static let artwork: [String: String] = [
'''
source += "\n".join(f'        {json.dumps(n)}: #"{svg}"#,' for n, _, svg in assets)
source += "\n    ]\n}\n"
(ROOT / "Sources/Barc/Folders/FolderSymbols.swift").write_text(source)
print(f"Updated {len(assets)} folder icons and their license from {REVISION}")
