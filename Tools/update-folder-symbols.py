#!/usr/bin/env python3
"""Refresh the pinned MIT-licensed Ionicons in the folder and Space pickers."""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from urllib.request import urlopen
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
REVISION = "d1e2c48641fd5f4910ee42a144dc1c84b1a9a4ee"
BASE = f"https://raw.githubusercontent.com/ionic-team/ionicons/{REVISION}"
ICONS = [
    ("star", "Star"), ("bookmark", "Bookmark"), ("heart", "Heart"), ("flash", "Lightning"),
    ("triangle", "Triangle"), ("medical", "Asterisk"), ("notifications", "Bell"), ("bulb", "Light bulb"),
    ("chatbubble-ellipses", "Chat"), ("people", "People"), ("construct", "Tools"), ("egg", "Egg"),
    ("ellipse", "Circle"), ("moon", "Moon"), ("planet", "Planet"), ("leaf", "Leaf"),
    ("cloud", "Cloud"), ("paw", "Paw"), ("restaurant", "Cutlery"), ("airplane", "Airplane"),
    ("musical-note", "Music"), ("videocam", "Video"), ("code", "Code"), ("skull", "Skull"),
]

def fetch(path):
    with urlopen(f"{BASE}/{path}", timeout=30) as response:
        return response.read().decode("utf-8")

def asset(icon):
    name, title = icon
    svg = " ".join(fetch(f"src/svg/{name}.svg").split())
    root = ET.fromstring(svg)
    assert root.tag.endswith("svg") and len(svg) < 65536
    assert "<script" not in svg and "href=" not in svg
    return name, title, svg

# Space source names follow Arc's saved iconType values. Folder choices stay at 24.
SPACE_NAMES = [
    "star", "bookmark", "heart", "flag", "flash", "triangle", "medical", "notifications",
    "bulb", "shapes", "grid", "apps", "layers", "server", "albums", "copy",
    "folder", "fileTrayFull", "calendar", "mail", "checkbox", "document", "book", "chatBubbleEllipses",
    "people", "terminal", "construction", "square", "egg", "ellipse", "moon", "sunny",
    "planet", "leaf", "cloud", "paw", "bag", "gift", "bed", "restaurant",
    "barbell", "airplane", "musicalNote", "colorPallete", "video", "bandage", "code", "baseball",
    "cloudOutline", "map", "bonfire", "pizza", "skull", "receipt", "thumbsUp", "train",
]
ALIASES = {"fileTrayFull": "file-tray-full", "chatBubbleEllipses": "chatbubble-ellipses",
    "construction": "construct", "bag": "basket", "musicalNote": "musical-note", "colorPallete": "color-palette",
    "video": "videocam", "cloudOutline": "cloud-outline", "thumbsUp": "thumbs-up"}
TITLES = {"medical": "Asterisk", "flash": "Lightning", "notifications": "Bell", "bulb": "Light bulb",
    "chatBubbleEllipses": "Chat", "construction": "Tools", "ellipse": "Circle", "fileTrayFull": "File tray",
    "musicalNote": "Music", "colorPallete": "Color palette", "cloudOutline": "Cloud outline", "thumbsUp": "Thumbs up"}
space_icons = [(ALIASES.get(n, n), TITLES.get(n, n[:1].upper() + n[1:])) for n in SPACE_NAMES]
FOOTER_ICONS = ["happy-outline", "sunny-outline", "cafe-outline", "ribbon-outline", "bus-outline", "gift-outline", "heart-outline", "flag-outline", "trash-outline"]
all_icons = dict(ICONS + space_icons + [("bag", "Bag")] + [(n, n) for n in FOOTER_ICONS])
with ThreadPoolExecutor(max_workers=8) as pool:
    assets = list(pool.map(asset, all_icons.items()))

license_path = ROOT / "LICENSES/Ionicons.txt"
license_path.parent.mkdir(exist_ok=True)
license_path.write_text(fetch("LICENSE"))

header = """// Modified for Barc: compact folder and Space icon palettes, 2026-10-24.
// SVG artwork: Ionicons, Copyright (c) 2015-present Ionic, MIT license.
// See LICENSES/Ionicons.txt. Generated by Tools/update-folder-symbols.py.
import AppKit

"""
source = header + """@MainActor
enum FolderSymbols {
    struct Choice {
        let name: String
        let title: String
        var storedName: String { "ionicon." + name }
    }
    static let choices: [Choice] = [
"""
source += "\n".join(f"        Choice(name: {json.dumps(n)}, title: {json.dumps(t)})," for n, t in ICONS)
source += """
    ]
    static func image(named name: String, description: String? = nil) -> NSImage? {
        SpaceSymbols.image(named: name, description: description)
    }
}
"""
(ROOT / "Sources/Barc/Folders/FolderSymbols.swift").write_text(source)
source = header + """enum SpaceSymbols {
    struct Choice: Equatable, Sendable {
        let sourceName: String
        let name: String
        let title: String
        var storedName: String { "ionicon." + name }
    }
    static let choices: [Choice] = [
"""
source += "\n".join(f"        Choice(sourceName: {json.dumps(n)}, name: {json.dumps(a)}, title: {json.dumps(t)})," for n, (a,t) in zip(SPACE_NAMES,space_icons))
source += """
    ]
    /// Arc uses camel-case enum values, including its original colorPallete spelling.
    static func storedName(forArcName name: String) -> String? {
        choices.first { $0.sourceName == name || $0.name == name }?.storedName
    }
    @MainActor private static var cache: [String: NSImage] = [:]

    /// Existing SF Symbols remain valid for previously customized icons.
    @MainActor static func image(named name: String, description: String? = nil) -> NSImage? {
        guard name.hasPrefix("ionicon.") else {
            return NSImage(systemSymbolName: name, accessibilityDescription: description)
        }
        let key = String(name.dropFirst("ionicon.".count))
        if let image = cache[key] { return image }
        guard let svg = artwork[key], let image = NSImage(data: Data(svg.utf8)) else { return nil }
        image.size = NSSize(width: 18, height: 18)
        image.isTemplate = true
        cache[key] = image
        return image
    }

    // Pinned source revision: """ + REVISION + """
    private static let artwork: [String: String] = [
"""
source += "\n".join(f'        {json.dumps(n)}: #"{svg}"#,' for n, _, svg in assets)
source += "\n    ]\n}\n"
(ROOT / "Sources/Barc/Spaces/SpaceSymbols.swift").write_text(source)
print(f"Updated {len(assets)} icons: {len(ICONS)} folder choices, {len(SPACE_NAMES)} Space choices from {REVISION}")
