#!/usr/bin/env python3
"""Refresh Unicode 15.1 emoji labels/order used by the compact Space picker."""
from pathlib import Path
from urllib.request import urlopen
import hashlib
import re

ROOT = Path(__file__).resolve().parent.parent
URL = 'https://unicode.org/Public/emoji/15.1/emoji-test.txt'
with urlopen(URL, timeout=30) as response:
    data = response.read()
GROUPS = {'Smileys & Emotion': 0, 'People & Body': 0, 'Animals & Nature': 1,
          'Food & Drink': 2, 'Activities': 3, 'Travel & Places': 4,
          'Objects': 5, 'Symbols': 6, 'Flags': 7}
entries = []
category = None
for line in data.decode('utf8').splitlines():
    if line.startswith('# group: '):
        category = GROUPS.get(line.removeprefix('# group: '))
    match = re.match(r'^([0-9A-F ]+)\s*; fully-qualified\s*# (\S+) E[0-9.]+ (.+)$', line)
    if not match or category is None:
        continue
    points, glyph, name = match.groups()
    # The compact palette shows the default presentation once. Skin tones
    # are not thousands of separate choices in the grid.
    if any(0x1F3FB <= int(cp, 16) <= 0x1F3FF for cp in points.split()):
        continue
    entries.append(f'{category}|{glyph}|{name}')
assert len(entries) > 1800
source = '''// Modified for Barc: searchable eight-category Space emoji palette, 2026-10-24.
// Emoji names and ordering: Unicode 15.1, Copyright © 2023 Unicode, Inc.
// See LICENSES/Unicode.txt. Generated by Tools/update-space-emoji.py.
// Source: ''' + URL + '\n// SHA-256: ' + hashlib.sha256(data).hexdigest() + '''
import Foundation

extension SpaceEmojiCatalog {
    static let entries: [Entry] = data.split(separator: "\\n").compactMap { line in
        let parts = line.split(separator: "|", maxSplits: 2)
        guard parts.count == 3, let raw = Int(parts[0]), let category = Category(rawValue: raw) else { return nil }
        return Entry(glyph: String(parts[1]), name: String(parts[2]), category: category)
    }
    private static let data = """
'''
source += '\n'.join(entries) + '\n"""\n}\n'
(ROOT / 'Sources/Barc/Spaces/SpaceEmojiData.swift').write_text(source)
with urlopen('https://www.unicode.org/license.txt', timeout=30) as response:
    (ROOT / 'LICENSES/Unicode.txt').write_bytes(response.read())
print(f'Updated {len(entries)} default emoji and their Unicode license')
